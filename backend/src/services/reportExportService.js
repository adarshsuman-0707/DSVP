const ExcelJS = require('exceljs');
const PDFDocument = require('pdfkit');

const BRAND_BLUE = '2E74B5';
const BRAND_BLUE_LIGHT = 'EFF6FF';

/* ═══════════════════════════════════════════════════════════════════════
   EXCEL
   ═══════════════════════════════════════════════════════════════════════ */
async function buildExcelBuffer({ title, columns, rows, summary }) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'DSVP';
  workbook.created = new Date();

  const sheet = workbook.addWorksheet(title ? title.slice(0, 31) : 'Report');
  let rowCursor = 1;

  if (title) {
    sheet.mergeCells(rowCursor, 1, rowCursor, columns.length || 1);
    const titleCell = sheet.getCell(rowCursor, 1);
    titleCell.value = title;
    titleCell.font = { bold: true, size: 14, color: { argb: 'FF' + BRAND_BLUE } };
    rowCursor += 2;
  }

  if (Array.isArray(summary) && summary.length) {
    summary.forEach(({ label, value }) => {
      const labelCell = sheet.getCell(rowCursor, 1);
      const valueCell = sheet.getCell(rowCursor, 2);
      labelCell.value = label;
      labelCell.font = { bold: true };
      valueCell.value = value;
      rowCursor += 1;
    });
    rowCursor += 1;
  }

  const headerRowNum = rowCursor;
  columns.forEach((col, idx) => {
    const cell = sheet.getCell(headerRowNum, idx + 1);
    cell.value = col.label;
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF' + BRAND_BLUE } };
    cell.alignment = { vertical: 'middle', horizontal: 'left' };
  });
  rowCursor += 1;

  rows.forEach((row, rIdx) => {
    columns.forEach((col, cIdx) => {
      const cell = sheet.getCell(rowCursor, cIdx + 1);
      let value = row[col.key];
      if (value instanceof Date) value = value;
      cell.value = value === undefined || value === null ? '' : value;
      if (rIdx % 2 === 1) {
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF' + BRAND_BLUE_LIGHT } };
      }
    });
    rowCursor += 1;
  });

  // Auto column widths (rough heuristic based on content length).
  columns.forEach((col, idx) => {
    const headerLen = (col.label || '').length;
    const maxDataLen = rows.reduce((max, row) => {
      const v = row[col.key];
      const len = v === undefined || v === null ? 0 : String(v).length;
      return Math.max(max, len);
    }, 0);
    sheet.getColumn(idx + 1).width = Math.min(Math.max(headerLen, maxDataLen, 10) + 2, 50);
  });

  const buffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(buffer);
}

/* ═══════════════════════════════════════════════════════════════════════
   PDF
   ═══════════════════════════════════════════════════════════════════════ */
function buildPdfBuffer({ title, userName, generatedAt, filtersApplied, summary, columns, rows }) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 40, bufferPages: true });
    const chunks = [];
    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;

    // Header wordmark — no logo asset in the repo, styled text stands in.
    doc.fontSize(20).fillColor(`#${BRAND_BLUE}`).font('Helvetica-Bold').text('DSVP', { continued: false });
    doc.moveDown(0.3);
    doc.fontSize(14).fillColor('#111111').font('Helvetica-Bold').text(title || 'Report');
    doc.moveDown(0.2);
    doc.fontSize(9).fillColor('#555555').font('Helvetica')
      .text(`Generated by: ${userName || 'Unknown'}`)
      .text(`Generated on: ${generatedAt || new Date().toISOString()}`);

    if (filtersApplied && Object.keys(filtersApplied).length) {
      const filterLine = Object.entries(filtersApplied)
        .filter(([, v]) => v !== undefined && v !== null && v !== '')
        .map(([k, v]) => `${k}: ${v}`)
        .join('  |  ');
      if (filterLine) {
        doc.moveDown(0.2);
        doc.fontSize(9).fillColor('#555555').text(`Filters: ${filterLine}`);
      }
    }

    doc.moveDown(0.5);

    if (Array.isArray(summary) && summary.length) {
      doc.fontSize(11).fillColor('#111111').font('Helvetica-Bold').text('Summary');
      doc.fontSize(9).font('Helvetica');
      summary.forEach(({ label, value }) => {
        doc.fillColor('#333333').text(`${label}: ${value}`);
      });
      doc.moveDown(0.5);
    }

    // Simple manual table.
    const colCount = columns.length || 1;
    const colWidth = pageWidth / colCount;
    const rowHeight = 16;
    const bottomLimit = doc.page.height - doc.page.margins.bottom - 20;

    function drawFooter(d) {
      const pages = d.bufferedPageRange();
      const pageNum = pages.count; // current page being drawn
      // Drawing inside the bottom margin would otherwise make pdfkit think
      // the text overflows the page and auto-insert another page (which
      // re-fires this same 'pageAdded' listener -> infinite recursion).
      // Temporarily zero the bottom margin while writing the footer line.
      const originalBottom = d.page.margins.bottom;
      const savedX = d.x;
      const savedY = d.y;
      d.page.margins.bottom = 0;
      d.fontSize(8).fillColor('#999999').text(
        `DSVP - Page ${pageNum}`,
        d.page.margins.left,
        d.page.height - originalBottom + 5,
        { width: pageWidth, align: 'center', lineBreak: false }
      );
      d.page.margins.bottom = originalBottom;
      d.x = savedX;
      d.y = savedY;
    }

    // Footer on every page, including the first.
    doc.on('pageAdded', () => drawFooter(doc));
    drawFooter(doc);

    function drawHeaderRow(y) {
      doc.fontSize(9).font('Helvetica-Bold').fillColor('#FFFFFF');
      doc.rect(doc.page.margins.left, y, pageWidth, rowHeight).fill(`#${BRAND_BLUE}`);
      columns.forEach((col, idx) => {
        doc.fillColor('#FFFFFF').text(
          col.label,
          doc.page.margins.left + idx * colWidth + 2,
          y + 4,
          { width: colWidth - 4, ellipsis: true }
        );
      });
    }

    let y = doc.y + 5;
    drawHeaderRow(y);
    y += rowHeight;

    doc.font('Helvetica').fontSize(8);
    rows.forEach((row, rIdx) => {
      if (y + rowHeight > bottomLimit) {
        doc.addPage();
        y = doc.page.margins.top;
        drawHeaderRow(y);
        y += rowHeight;
      }
      if (rIdx % 2 === 1) {
        doc.rect(doc.page.margins.left, y, pageWidth, rowHeight).fill(`#${BRAND_BLUE_LIGHT}`);
      }
      columns.forEach((col, idx) => {
        let value = row[col.key];
        if (value instanceof Date) value = value.toISOString().slice(0, 19).replace('T', ' ');
        value = value === undefined || value === null ? '' : String(value);
        doc.fillColor('#111111').text(
          value,
          doc.page.margins.left + idx * colWidth + 2,
          y + 4,
          { width: colWidth - 4, height: rowHeight - 2, ellipsis: true }
        );
      });
      y += rowHeight;
    });

    doc.end();
  });
}

/* ═══════════════════════════════════════════════════════════════════════
   CSV — hand-rolled RFC4180 quoting, no dependency needed.
   ═══════════════════════════════════════════════════════════════════════ */
function csvEscape(value) {
  if (value === undefined || value === null) return '';
  let str = value instanceof Date ? value.toISOString() : String(value);
  if (/[",\n\r]/.test(str)) {
    str = '"' + str.replace(/"/g, '""') + '"';
  }
  return str;
}

function buildCsv({ columns, rows }) {
  const header = columns.map((c) => csvEscape(c.label)).join(',');
  const lines = rows.map((row) => columns.map((c) => csvEscape(row[c.key])).join(','));
  return [header, ...lines].join('\r\n');
}

module.exports = { buildExcelBuffer, buildPdfBuffer, buildCsv };
